const listPage = document.getElementById("listPage");
const detailPage = document.getElementById("detailPage");
const productList = document.getElementById("productList");
const tabButtons = document.querySelectorAll(".tab-btn");
const tabList = document.getElementById("tabList");

const backBtn = document.getElementById("backBtn");
const detailImage = document.getElementById("detailImage");
const detailTitle = document.getElementById("detailTitle");
const detailDesc = document.getElementById("detailDesc");
const detailPrice = document.getElementById("detailPrice");
const orderBtn = document.getElementById("orderBtn");

function renderProducts(category = "all") {
  productList.innerHTML = "";

  const selectedProducts = productsByCategory[category];

  selectedProducts.forEach((product) => {
    const li = document.createElement("li");
    li.className = "product-card";

    li.innerHTML = `
      <button type="button" class="product-card-btn" data-category="${category}" data-id="${product.id}">
        <div class="product-thumb">
          <img src="${product.image}" alt="${product.name}">
        </div>

        <div class="product-info">
          <h2 class="product-name">${product.name}</h2>
          <strong class="product-price">${product.price}</strong>
        </div>

        <span class="bookmark" role="button" tabindex="0" aria-label="북마크" aria-pressed="false"></span>
      </button>
    `;

    productList.appendChild(li);
  });

  const productButtons = document.querySelectorAll(".product-card-btn");

  productButtons.forEach((button) => {
    button.addEventListener("click", (event) => {
      if (event.target.closest(".bookmark")) return;

      const productId = button.dataset.id;
      const category = button.dataset.category;

      openDetailPage(category, productId);
    });
  });

  const bookmarkButtons = document.querySelectorAll(".bookmark");

  bookmarkButtons.forEach((bookmark) => {
    bookmark.addEventListener("click", (event) => {
      event.stopPropagation();

      bookmark.classList.toggle("active");
      bookmark.setAttribute("aria-pressed", bookmark.classList.contains("active"));
    });

    bookmark.addEventListener("keydown", (event) => {
      if (event.key !== "Enter" && event.key !== " ") return;

      event.preventDefault();
      event.stopPropagation();

      bookmark.classList.toggle("active");
      bookmark.setAttribute("aria-pressed", bookmark.classList.contains("active"));
    });
  });
}

function openDetailPage(category, productId) {
  const product = productsByCategory[category].find((item) => item.id === productId);

  if (!product) return;

  detailImage.src = product.image;
  detailImage.alt = product.name;
  detailTitle.textContent = product.name;
  detailDesc.textContent = product.desc;
  detailPrice.textContent = product.price;

  orderBtn.href = '#';

  listPage.classList.remove("active");
  detailPage.classList.add("active");

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });
}

backBtn.addEventListener("click", () => {
  detailPage.classList.remove("active");
  listPage.classList.add("active");

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });
});

tabButtons.forEach((button) => {
  button.addEventListener("click", () => {
    tabButtons.forEach((btn) => btn.classList.remove("active"));
    button.classList.add("active");

    const category = button.dataset.category;
    renderProducts(category);
  });
});

/* tab 메뉴 grab 가로 스크롤 */
let isDown = false;
let startX = 0;
let scrollLeft = 0;

tabList.addEventListener("mousedown", (event) => {
  isDown = true;
  tabList.classList.add("dragging");
  startX = event.pageX - tabList.offsetLeft;
  scrollLeft = tabList.scrollLeft;
});

tabList.addEventListener("mouseleave", () => {
  isDown = false;
  tabList.classList.remove("dragging");
});

tabList.addEventListener("mouseup", () => {
  isDown = false;
  tabList.classList.remove("dragging");
});

tabList.addEventListener("mousemove", (event) => {
  if (!isDown) return;

  event.preventDefault();

  const x = event.pageX - tabList.offsetLeft;
  const walk = (x - startX) * 1.4;

  tabList.scrollLeft = scrollLeft - walk;
});

/* 모바일 터치 스크롤 보정 */
let touchStartX = 0;
let touchScrollLeft = 0;

tabList.addEventListener("touchstart", (event) => {
  touchStartX = event.touches[0].pageX;
  touchScrollLeft = tabList.scrollLeft;
});

tabList.addEventListener("touchmove", (event) => {
  const touchX = event.touches[0].pageX;
  const moveX = touchX - touchStartX;

  tabList.scrollLeft = touchScrollLeft - moveX;
});

